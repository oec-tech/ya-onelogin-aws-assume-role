"""
--init-profiles: after one login, lists every AWS role the user has, looks up
the account names (IAM account aliases), and writes a 'generated:' block with
a profile per role into config.yaml. Settings written outside that block win
over it, so hand-made names and profiles are kept when it is regenerated.
"""

import os
import re

import boto3
import botocore.client
import yaml

try:
    from aws_assume_role import ui
except ImportError:
    import ui

BEGIN_MARKER = "# >>> generated by olaar --init-profiles: rerun it to refresh, edits in this block are replaced"
END_MARKER = "# <<< end of generated block"
DEFAULT_CONFIG_PATH = os.path.join(os.path.expanduser('~'), '.onelogin', 'config.yaml')


def parse_role(role_string):
    """
    Returns (account id, role name, role ARN, principal ARN) of a SAML role string.
    """
    role_arn, principal_arn = role_string.split(",")[:2]
    parts = role_arn.split(":")
    return parts[4], parts[5].replace("role/", ""), role_arn, principal_arn


def lookup_account_names(roles, saml_response, region, sts_client=None, iam_factory=None):
    """
    Returns {account id: alias} for the accounts whose alias one of the user's
    roles there may read. Tries the roles of each account until one works.
    """
    sts = sts_client or boto3.client('sts', region_name=region,
                                     config=botocore.client.Config(signature_version=botocore.UNSIGNED))
    iam_factory = iam_factory or (lambda credentials: boto3.client(
        'iam', aws_access_key_id=credentials['AccessKeyId'], aws_secret_access_key=credentials['SecretAccessKey'],
        aws_session_token=credentials['SessionToken']))
    by_account = {}
    for role in roles:
        account_id, _, role_arn, principal_arn = parse_role(role)
        by_account.setdefault(account_id, []).append((role_arn, principal_arn))
    names = {}
    for account_id, account_roles in sorted(by_account.items()):
        for role_arn, principal_arn in account_roles:
            try:
                token = sts.assume_role_with_saml(RoleArn=role_arn, PrincipalArn=principal_arn,
                                                  SAMLAssertion=saml_response, DurationSeconds=900)
                aliases = iam_factory(token['Credentials']).list_account_aliases().get('AccountAliases') or []
            except Exception:
                continue
            if aliases:
                names[account_id] = aliases[0]
            break
    return names


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', str(text).lower()).strip('-')


def generate(roles, account_names):
    """
    Returns the 'generated' block: account names, and one profile per role
    named <account name or id>-<role>.
    """
    profiles = {}
    for role in sorted(roles):
        account_id, role_name, _, _ = parse_role(role)
        base = "%s-%s" % (slug(account_names.get(account_id, account_id)), slug(role_name))
        name, counter = base, 2
        while name in profiles:
            name, counter = "%s-%s" % (base, counter), counter + 1
        profiles[name] = {'aws-account-id': account_id, 'aws-role-name': role_name}
    return {'accounts': dict(sorted(account_names.items())), 'profiles': profiles}


class _QuotedDumper(yaml.SafeDumper):
    pass


def _represent_str(dumper, value):
    # Quote account ids so YAML keeps them as text with their leading zeros
    style = '"' if value.isdigit() else None
    return dumper.represent_scalar('tag:yaml.org,2002:str', value, style=style)


_QuotedDumper.add_representer(str, _represent_str)


def render_block(block):
    body = yaml.dump({'generated': block}, Dumper=_QuotedDumper, default_flow_style=False, sort_keys=False)
    return "%s\n%s%s\n" % (BEGIN_MARKER, body, END_MARKER)


def write_block(path, block_text):
    """
    Replaces the generated block in the config file, or appends it, leaving
    everything else in the file as it was. Returns True when the file existed.
    """
    try:
        with open(path) as f:
            text = f.read()
        existed = True
    except FileNotFoundError:
        text, existed = "", False
    start = text.find(BEGIN_MARKER)
    end = text.find(END_MARKER)
    if start != -1 and end > start:
        text = text[:start] + block_text + text[end + len(END_MARKER):].lstrip("\n")
    else:
        text = text.rstrip("\n") + ("\n\n" if text.strip() else "") + block_text
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)
    return existed


def init_profiles(roles, saml_response, options, region):
    """
    Writes the generated block for these roles and prints what it did.
    """
    roles = [role for role in roles if role and len(role.split(",")) >= 2 and role.split(",")[1]]
    with ui.waiting("Looking up the account names..."):
        account_names = lookup_account_names(roles, saml_response, region)
    # Names you gave under 'accounts:' win over the aliases, also in the profile names
    own_names = getattr(options, 'own_account_names', None) or {}
    block = generate(roles, dict(account_names, **own_names))
    block['accounts'] = dict(sorted(account_names.items()))
    path = options.config or DEFAULT_CONFIG_PATH
    write_block(path, render_block(block))

    manual = set(getattr(options, 'yaml_profiles', {}) or {}) - set(getattr(options, 'generated_profiles', set()) or set())
    rows = []
    for name, values in block['profiles'].items():
        account_id = values['aws-account-id']
        name_of = own_names.get(account_id) or account_names.get(account_id)
        account = "%s (%s)" % (account_id, name_of) if name_of else account_id
        rows.append((name + (" (+ your settings)" if name in manual else ""), account, values['aws-role-name']))
    ui.table("Generated profiles", ["Name (-p)", "Account", "Role"], rows)
    missing = sorted({values['aws-account-id'] for values in block['profiles'].values()}
                     - set(account_names) - set(own_names))
    if missing:
        ui.note("No account name for %s: no alias set, or your roles there can't read it (iam:ListAccountAliases). "
                "Name them under 'accounts:' in the config." % ", ".join(missing))
    ui.ok("Wrote %s profiles to the 'generated:' block of %s" % (len(block['profiles']), path))
    ui.note("Your own 'profiles:' and 'accounts:' win over these. Rerun --init-profiles to refresh them.")
